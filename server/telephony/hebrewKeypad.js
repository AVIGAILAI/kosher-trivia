/**
 * הקלדת שם בעברית במקשי טלפון — למחייגות שאינן ברשימת השמות
 * (החליפו פלאפון היום / מצטרפות חדשות שלא בכיתה).
 *
 * הקידוד: שתי ספרות לכל אות — קודם המקש שעליו האות מופיעה (כמו שמודפס על
 * הפלאפון), ואז 1/2/3 לפי מיקום האות על המקש. אפס = רווח. סולמית = סיום.
 * זהו הקידוד הדטרמיניסטי היחיד שעובד מעל איסוף ספרות (בלי תלות בתזמון הקשות).
 */

// פריסת אותיות סטנדרטית על מקשי הטלפון (לפי הסדר המודפס על המקש)
const KEY_LETTERS = {
  2: ['א', 'ב', 'ג'],
  3: ['ד', 'ה', 'ו'],
  4: ['ז', 'ח', 'ט'],
  5: ['י', 'כ', 'ל'],
  6: ['מ', 'נ', 'ס'],
  7: ['ע', 'פ', 'צ'],
  8: ['ק', 'ר', 'ש'],
  9: ['ת'],
};

// המרת אות רגילה לצורתה הסופית (בסוף מילה)
const FINALS = { כ: 'ך', מ: 'ם', נ: 'ן', פ: 'ף', צ: 'ץ' };

export const KEYPAD_INSTRUCTIONS =
  'להקלדת שמך: לכל אות הקישי את המקש שעליו האות מופיעה, ואחריו הקישי 1, 2 או 3 ' +
  'לפי מיקום האות על המקש — 1 לראשונה, 2 לאמצעית, 3 לשלישית. ' +
  'לרווח הקישי אפס. למחיקה הקישי כוכבית. בסיום הקישי סולמית';

/**
 * מפענח מחרוזת ספרות לשם עברי. סלחני: מיקום חסר/שגוי → האות הראשונה במקש;
 * ספרות לא-חוקיות (1) מדולגות; אות בסוף מילה מומרת לצורה סופית.
 */
export function decodeHebrewName(rawDigits) {
  const s = String(rawDigits || '').replace(/[^0-9]/g, '');
  const out = [];
  let i = 0;
  while (i < s.length) {
    const d = s[i];
    if (d === '0') { out.push(' '); i++; continue; }   // רווח
    if (d === '1') { i++; continue; }                   // 1 לא בשימוש
    const group = KEY_LETTERS[d];
    if (!group) { i++; continue; }
    let pos = parseInt(s[i + 1], 10);
    if (!(pos >= 1 && pos <= group.length)) pos = 1;    // ברירת מחדל: אות ראשונה
    out.push(group[pos - 1]);
    i += 2;
  }
  // המרת אותיות סופיות (בסוף מילה) + ניקוי רווחים
  const name = out.join('').replace(/([כמנפצ])(?=$|\s)/g, (m) => FINALS[m] || m);
  return name.replace(/\s+/g, ' ').trim().slice(0, 40);
}
